package org.wso2.integrator.perf.spring;

import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.MediaType;
import org.springframework.web.reactive.function.server.RouterFunction;
import org.springframework.web.reactive.function.server.ServerResponse;

import static org.springframework.web.reactive.function.server.RequestPredicates.GET;
import static org.springframework.web.reactive.function.server.RouterFunctions.route;

/** Hello-world scenario: {@code GET /hello} returns a fixed body. */
@Configuration
@ConditionalOnProperty(name = "scenario", havingValue = "hello", matchIfMissing = true)
public class HelloConfig {

    @Bean
    public RouterFunction<ServerResponse> helloRoute() {
        return route(GET("/hello"), request -> ServerResponse.ok()
                .contentType(MediaType.TEXT_PLAIN)
                .bodyValue("Hello, World!"));
    }
}
